/*
 * One-time helper: reads data.js, finds every unique Chinese character used,
 * and downloads its stroke-order data from the Hanzi Writer data CDN into
 * ./hanzi-data/<char>.json so the app works fully offline afterwards.
 *
 * Run with:  node fetch-hanzi-data.js
 * Safe to re-run after adding new lessons — it skips files already present.
 */
const fs = require("fs");
const path = require("path");
const https = require("https");

// Load VOCAB by evaluating data.js in a tiny sandbox.
const dataSrc = fs.readFileSync(path.join(__dirname, "data.js"), "utf8");
const sandbox = { window: {} };
new Function("window", dataSrc)(sandbox.window);
const VOCAB = sandbox.window.VOCAB;

const chars = new Set();
for (const lesson of VOCAB.lessons)
  for (const w of lesson.words)
    for (const ch of w.hanzi)
      if (/[一-鿿]/.test(ch)) chars.add(ch);

const outDir = path.join(__dirname, "hanzi-data");
fs.mkdirSync(outDir, { recursive: true });

const VERSION = "2.0.1";
function fetchChar(ch) {
  return new Promise((resolve) => {
    const out = path.join(outDir, ch + ".json");
    if (fs.existsSync(out) && fs.statSync(out).size > 0) return resolve("skip");
    const url = `https://cdn.jsdelivr.net/npm/hanzi-writer-data@${VERSION}/${encodeURIComponent(ch)}.json`;
    https.get(url, (res) => {
      if (res.statusCode !== 200) { res.resume(); return resolve("MISS " + res.statusCode); }
      let body = "";
      res.on("data", (d) => (body += d));
      res.on("end", () => {
        try { JSON.parse(body); fs.writeFileSync(out, body); resolve("ok"); }
        catch { resolve("BADJSON"); }
      });
    }).on("error", (e) => resolve("ERR " + e.message));
  });
}

(async () => {
  const list = [...chars];
  console.log(`Unique characters: ${list.length}`);
  let ok = 0, skip = 0, miss = [];
  for (const ch of list) {
    const r = await fetchChar(ch);
    if (r === "ok") ok++;
    else if (r === "skip") skip++;
    else miss.push(`${ch}:${r}`);
  }
  console.log(`Downloaded ${ok}, already had ${skip}.`);
  if (miss.length) console.log("MISSING:", miss.join("  "));
  else console.log("All characters have stroke data. ✔");

  // Bundle every downloaded JSON into one hanzi-data.js so the app needs no
  // network AND no fetch() — works even when opened directly as a file://.
  const bundle = {};
  for (const ch of list) {
    const f = path.join(outDir, ch + ".json");
    if (fs.existsSync(f)) bundle[ch] = JSON.parse(fs.readFileSync(f, "utf8"));
  }
  const js = "/* Auto-generated by fetch-hanzi-data.js — do not edit by hand. */\n" +
             "window.HANZI_DATA = " + JSON.stringify(bundle) + ";\n";
  fs.writeFileSync(path.join(__dirname, "hanzi-data.js"), js);
  console.log(`Wrote hanzi-data.js (${Object.keys(bundle).length} chars, ${(js.length/1024).toFixed(0)} KB).`);
})();
